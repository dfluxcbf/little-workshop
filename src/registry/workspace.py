"""The Claude Code files of the workspace around the projects: the `little-projects` root session and
little-workshop's own session (REQ-000000543, REQ-000000544, REQ-000000546).

- Both read every registered checkout without a prompt (`Read(//<checkout>/**)` rules: reads only, so the
  projects' skills and instructions do not load into these sessions as an added directory's would).
- The root writes in a checkout as that project's own session would: `Edit(//<checkout>/**)` is pre-allowed and
  the root guard hands every write, and every command run inside a checkout, to that project's own guard.
- The root delegates work inside a project to a sub-session there (`tools/project_session.py`, the
  `project-session` skill), one per project, resumed while it can be.

little-workshop's own writes in other projects are judged by its guard's `--platform` mode
(`claude_templates.py`). `tools/sync_workspace_claude.py` writes these files; the root's `.claude/` and
little-workshop's `settings.local.json` are per-machine and stay out of git.
"""

from __future__ import annotations

import json
import os

ROOT_GUARD_PATH = ".claude/hooks/root_guard.py"
ROOT_SKILL_PATH = ".claude/skills/project-session/SKILL.md"
SESSION_TOOL = "little-workshop/tools/project_session.py"
GUARD = ".claude/hooks/lws_scope_guard.py"
EDIT_TOOLS = ("Edit", "Write", "MultiEdit", "NotebookEdit")


def _rule_path(path: str) -> str:
    """An absolute path as a permission rule writes it (`//abs/path`)."""
    return "/" + os.path.normpath(path)


def read_rules(projects: dict[str, str]) -> list[str]:
    return [f"Read({_rule_path(path)}/**)" for path in sorted(projects.values())]


def edit_rules(projects: dict[str, str]) -> list[str]:
    return [f"Edit({_rule_path(path)}/**)" for path in sorted(projects.values())]


def _is_checkout_rule(rule: str, kinds: tuple[str, ...]) -> bool:
    """A rule this module writes: `Read(//abs/**)` or `Edit(//abs/**)` naming one folder."""
    return any(rule.startswith(f"{kind}(//") for kind in kinds) and rule.endswith("/**)")


def _merge_allow(allow: list[str], generated: list[str], kinds: tuple[str, ...]) -> list[str]:
    kept = [rule for rule in allow if not _is_checkout_rule(rule, kinds)]
    return kept + [rule for rule in generated if rule not in kept]


def root_guard_hook(root: str) -> dict:
    return {"matcher": "|".join(("Bash", *EDIT_TOOLS)),
            "hooks": [{"type": "command", "command": f"python3 {os.path.join(root, ROOT_GUARD_PATH)}", "timeout": 15}]}


def root_settings(current: dict | None, projects: dict[str, str], root: str) -> dict:
    """The root's `.claude/settings.json`: `current` with every checkout readable and writable, the sub-session
    tool pre-allowed and the root guard registered (the root's other entries kept)."""
    out = json.loads(json.dumps(current or {}))
    permissions = out.setdefault("permissions", {})
    session = [f"Bash(python3 {SESSION_TOOL}*)", f"Bash(python3 {os.path.join(root, SESSION_TOOL)}*)"]
    kept = [rule for rule in permissions.get("allow", []) if rule not in session]
    permissions["allow"] = _merge_allow(kept, read_rules(projects) + edit_rules(projects) + session, ("Read", "Edit"))
    pre = [e for e in out.setdefault("hooks", {}).get("PreToolUse", [])
           if not any("root_guard.py" in h.get("command", "") for h in e.get("hooks", []))]
    out["hooks"]["PreToolUse"] = [root_guard_hook(root), *pre]
    return out


def workshop_local_settings(current: dict | None, projects: dict[str, str]) -> dict:
    """little-workshop's `.claude/settings.local.json`: `current` with every other checkout readable."""
    out = json.loads(json.dumps(current or {}))
    permissions = out.setdefault("permissions", {})
    others = {name: path for name, path in projects.items() if name != "little-workshop"}
    permissions["allow"] = _merge_allow(permissions.get("allow", []), read_rules(others), ("Read",))
    return out


_ROOT_GUARD = r'''#!/usr/bin/env python3
"""PreToolUse hook of the little-projects root session: a write in a project's checkout, or a command run
inside one, is judged by that project's own guard, as if the session were started there.
Generated by little-workshop (src/registry/workspace.py, tools/sync_workspace_claude.py); do not edit."""

import json
import os
import shlex
import subprocess
import sys

PROJECTS = @@PROJECTS@@
GUARD = @@GUARD@@
EDIT_TOOLS = @@EDIT_TOOLS@@


def project_of(path):
    path = os.path.realpath(path)
    for name, root in sorted(PROJECTS.items(), key=lambda item: -len(item[1])):
        root = os.path.realpath(root)
        if path == root or path.startswith(root + os.sep):
            return name, root
    return None


def command_dir(command, cwd):
    """Where a Bash command runs: a leading `cd DIR`, else the session's directory."""
    try:
        words = shlex.split(command.split("&&", 1)[0].split(";", 1)[0])
    except ValueError:
        return cwd
    if len(words) >= 2 and words[0] == "cd":
        return os.path.join(cwd, os.path.expanduser(words[1]))
    return cwd


def main():
    try:
        event = json.load(sys.stdin)
        tool, args = event["tool_name"], event.get("tool_input") or {}
    except (ValueError, KeyError, TypeError):
        return
    cwd = event.get("cwd") or os.getcwd()
    if tool in EDIT_TOOLS:
        path = args.get("file_path") or args.get("notebook_path")
        target = project_of(path if os.path.isabs(str(path)) else os.path.join(cwd, str(path))) if path else None
    elif tool == "Bash":
        where = command_dir(str(args.get("command", "")), cwd)
        target = project_of(where)
        if target:
            event = {**event, "cwd": where}
    else:
        return
    if not target:
        return
    name, root = target
    guard = os.path.join(root, GUARD)
    if not os.path.isfile(guard):
        return
    done = subprocess.run([sys.executable, guard, name], input=json.dumps(event), capture_output=True, text=True,
                          env={**os.environ, "CLAUDE_PROJECT_DIR": root}, timeout=12)
    sys.stdout.write(done.stdout)


if __name__ == "__main__":
    main()
'''


def root_guard_py(projects: dict[str, str]) -> str:
    return (_ROOT_GUARD.replace("@@PROJECTS@@", json.dumps(dict(sorted(projects.items())), indent=4))
            .replace("@@GUARD@@", repr(GUARD)).replace("@@EDIT_TOOLS@@", repr(EDIT_TOOLS)))


PROJECT_SESSION_SKILL = f"""---
name: project-session
description: Runs work inside one project through a Claude sub-session started in that project's checkout (its own settings, briefing, skills and guard), resumed for later work on the same project, and returns its report. Use for any code, test, branch or Blender/Unity work inside a project instead of editing it from the root.
---

# Work inside a project through its sub-session

The user stays in this root session. Work inside a project runs in a sub-session started in its checkout, so
that project's rules apply exactly as if the user had opened it there:

```
python3 {SESSION_TOOL} <project-id> <<'EOF'
<the task: goal, constraints, what to report>
EOF
```

- One sub-session per project, resumed on every call (the tool keeps its id); `--new` only when the earlier one is
  about unrelated work or broken. `--status` lists them, `--forget <project-id>` drops one.
- Windows-hosted projects run the Windows `claude.exe`, so their Windows tools (Blender, Unity, git.exe) work.
- A long task: run the command in the background (`run_in_background`) and read the report when it ends.
- The report gives the sub-session's final message, its session id and any permission denials. A denial the
  user's request already covers: run it again with `--allow '<rule>'` (for example `--allow 'Bash(npm test*)'`)
  and the prompt `continue`. Ask the user only for a decision that is really theirs.
- Relay the outcome in a few lines; do not paste the whole report.
"""


def project_session_skill_md() -> str:
    return PROJECT_SESSION_SKILL
